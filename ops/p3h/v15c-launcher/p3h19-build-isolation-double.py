#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""P3-H Phase 19 / Task D: build the isolation test double of the patched launcher.

WHY THIS EXISTS
---------------
start_fde_v15c_classroom.patched-v3.ps1 has no path or port parameters: $StateRoot,
$V15Root, $DjangoPython, $DjangoPort, $RagPort and the instance mutex name are
hard-coded to production values. Running it as-is would (a) write the production
PID state record, (b) touch the live 8022 listener and (c) still contain the two
pre-existing cloudflared Stop-Process calls, which would kill the real tunnel.
Fault injection therefore cannot use the production file.

This builder produces a derived double that changes ONLY the configuration block
and truncates the script after the 8022 decision + state-write block. The logic
under test (the 8022 ownership/adoption/abort branch and the state record write)
stays byte-identical, and the builder proves it.

The double is a test artefact. It is never deployed and never replaces the patch.
"""

import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "start_fde_v15c_classroom.patched-v3.ps1")
DST = os.path.join(HERE, "start_fde_v15c_classroom.patched-v3.isolation.ps1")
REPORT = os.path.join(HERE, "BUILD_PHASE19_ISOLATION_DOUBLE.json")

# 1-based inclusive line range of the configuration block that gets replaced.
CFG_START = 8    # $GatewayRoot = Split-Path -Parent ...
CFG_END = 37     # $EnableAdoption = $true
# The double ends right after the state-write block.
CUT_AFTER = 250  # closing brace of the `if ($startedListener) { ... }` block

ISOLATION_CFG = r"""$GatewayRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
# ---------------------------------------------------------------------------
# P3-H PHASE 19 ISOLATION TEST DOUBLE - NOT FOR DEPLOYMENT.
# Generated by p3h19-build-isolation-double.py from
# start_fde_v15c_classroom.patched-v3.ps1. Only this configuration block differs;
# every line of the 8022 decision branch and the state-write block below is
# byte-identical to the patch under test.
# ---------------------------------------------------------------------------
$V15Root = Join-Path $GatewayRoot 'iso_project'
$DjangoPython = Join-Path $GatewayRoot 'iso_project\.venv\Scripts\python.exe'
$PythonLauncher = Join-Path $GatewayRoot 'iso_project\.venv\Scripts\python.exe'
$NpxCommand = 'npx.cmd'
$FfmpegBin = Join-Path $GatewayRoot 'iso_tools'
$FfmpegExecutable = Join-Path $FfmpegBin 'ffmpeg.exe'
$FfprobeExecutable = Join-Path $FfmpegBin 'ffprobe.exe'
$env:DJANGO_DB_NAME = Join-Path $GatewayRoot 'iso_state\iso.sqlite3'
$env:DJANGO_MEDIA_ROOT = Join-Path $GatewayRoot 'iso_state\media'
$env:DJANGO_FFMPEG_BINARY = $FfmpegExecutable
$env:DJANGO_FFPROBE_BINARY = $FfprobeExecutable
$RagRoot = Join-Path $GatewayRoot 'iso_rag'
$DjangoPort = 18022
$RagPort = 18770
$WorkerName = 'fde-ai-gateway-iso'
$FixedUrl = 'https://iso.invalid'
$StateRoot = Join-Path $GatewayRoot 'iso_state'
$LogRoot = Join-Path $GatewayRoot 'iso_logs'
$TunnelUrlFile = Join-Path $StateRoot 'current-tunnel-url.txt'
$StartupErrorLog = Join-Path $StateRoot 'startup-error.log'
$StartupLog = Join-Path $StateRoot 'startup.log'
$TunnelStateFile = Join-Path $StateRoot 'tunnel-state.json'
$InstanceMutexName = 'Local\FDE-AI-v15C-Classroom-Startup-ISOLATION-P3H19'
$DjangoPidStateFile = Join-Path $StateRoot 'django-v15c-pid.json'
# P3-H Phase 18 scheme switch. $true = controlled adoption of a pre-existing
# listener (scheme B). $false = require a stopped 8022 before the first run
# (scheme A). Both keep the no-auto-kill rule.
$EnableAdoption = $true"""

EPILOGUE = r"""
# P3-H Phase 19 isolation double: stop here. The RAG, network, cloudflared and
# wrangler sections of the production script are intentionally not reproduced.
Add-Content -LiteralPath $StartupLog -Value "$(Get-Date -Format o) ISO COMPLETE django_port=$DjangoPort state=$DjangoPidStateFile"
exit 0
"""


def sha(b):
    return hashlib.sha256(b).hexdigest()


def main():
    raw = open(SRC, "rb").read()
    text = raw.decode("utf-8")
    lines = text.splitlines()

    if len(lines) < CUT_AFTER:
        print("FATAL source shorter than expected: %d lines" % len(lines))
        return 2

    cfg_old = lines[CFG_START - 1:CFG_END]
    if not cfg_old[0].startswith("$GatewayRoot"):
        print("FATAL unexpected first config line: %r" % cfg_old[0])
        return 2
    if cfg_old[-1].strip() != "$EnableAdoption = $true":
        print("FATAL unexpected last config line: %r" % cfg_old[-1])
        return 2

    head = ISOLATION_CFG.splitlines()
    middle = lines[CFG_END:CUT_AFTER]          # lines 38..250, must stay identical
    out_lines = head + middle + EPILOGUE.splitlines()
    out_text = "\n".join(out_lines) + "\n"

    # non-ASCII / BOM guards: PowerShell 5.1 -File requires ASCII-only, no BOM
    non_ascii = [i + 1 for i, l in enumerate(out_lines) if any(ord(c) > 127 for c in l)]
    if non_ascii:
        print("FATAL non-ASCII lines: %s" % non_ascii[:10])
        return 2

    out_bytes = out_text.encode("ascii")
    open(DST, "wb").write(out_bytes)

    # ---- prove the logic under test is byte-identical ----
    src_middle = "\n".join(lines[CFG_END:CUT_AFTER])
    dst_lines = out_text.splitlines()
    dst_middle = "\n".join(dst_lines[len(head):len(head) + len(middle)])
    identical = sha(src_middle.encode()) == sha(dst_middle.encode())

    # ---- prove the double contains no termination primitive at all ----
    # Only real primitives count. The words "no auto-kill" appear in comments and
    # in the abort messages, so a bare `kill` substring test would false-positive.
    term_re = re.compile(r"(Stop-Process|taskkill|\.Kill\s*\(|\bspps\b|\bkill\.exe\b)",
                         re.IGNORECASE)
    term_hits = [l.strip() for l in dst_lines if term_re.search(l)]
    kill_words = [l.strip() for l in dst_lines if re.search(r"\bkill\b", l, re.IGNORECASE)]

    report = {
        "source": os.path.basename(SRC),
        "source_sha256": sha(raw),
        "source_lines": len(lines),
        "double": os.path.basename(DST),
        "double_sha256": sha(out_bytes),
        "double_lines": len(dst_lines),
        "double_bytes": len(out_bytes),
        "config_block_replaced": {"from_line": CFG_START, "to_line": CFG_END,
                                  "old_line_count": len(cfg_old),
                                  "new_line_count": len(head)},
        "logic_block_lines": {"from": CFG_END + 1, "to": CUT_AFTER,
                              "count": len(middle)},
        "logic_block_byte_identical": identical,
        "termination_primitives_in_double": term_hits,
        "kill_word_occurrences": kill_words,
        "non_ascii_lines": non_ascii,
        "bom": out_bytes.startswith(b"\xef\xbb\xbf"),
        "isolation_values": {
            "DjangoPort": 18022,
            "RagPort": 18770,
            "StateRoot": "<GatewayRoot>\\iso_state",
            "V15Root": "<GatewayRoot>\\iso_project",
            "MutexName": "Local\\FDE-AI-v15C-Classroom-Startup-ISOLATION-P3H19",
        },
    }
    with open(REPORT, "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)

    print("SOURCE  %s lines=%d sha=%s" % (os.path.basename(SRC), len(lines), sha(raw)[:16]))
    print("DOUBLE  %s lines=%d sha=%s" % (os.path.basename(DST), len(dst_lines), sha(out_bytes)[:16]))
    print("CONFIG  replaced lines %d..%d (%d -> %d lines)"
          % (CFG_START, CFG_END, len(cfg_old), len(head)))
    print("LOGIC   lines %d..%d (%d lines) byte-identical=%s"
          % (CFG_END + 1, CUT_AFTER, len(middle), identical))
    print("TERM    termination primitives in double: %d %s"
          % (len(term_hits), term_hits[:3]))
    print("ASCII   non_ascii_lines=%d bom=%s" % (len(non_ascii), report["bom"]))
    ok = identical and not term_hits and not non_ascii and not report["bom"]
    print("RESULT  %s" % ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
